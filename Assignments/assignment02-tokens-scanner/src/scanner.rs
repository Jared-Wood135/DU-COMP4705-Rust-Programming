/// About
/// -----
/// - Determines if a given character is a legitimate base 10 digit or not
/// - Rust has a library function to do this, so this is a one-line function
///
/// Parameters
/// ----------
/// - c (char)
///     - Character to check if it is a legitimate base 10 digit or not
///
/// Panics
/// ------
/// - NA
///
/// Output
/// ------
/// - bool
///     - true if `c` is a legitimate base 10 digit
///     - false otherwise
fn is_digit(c: char) -> bool{
    c.is_ascii_digit()
}

/// About
/// -----
/// - Determines if a given character could be part of an identifier (variable or function name in Lox)
/// - Such a character could be 'A' through 'Z', 'a' through 'z' or a '_' (underscore) character
/// - Rust has a library function to determine if a character is alphabetic, so this is a one-line function
/// 
/// Parameters
/// ----------
/// - c (char)
///     - Character to check if it is part of an identifier
/// 
/// Panics
/// ------
/// - None
/// 
/// Returns
/// -------
/// - bool
///     - true if `c` could be part of an identifier
///     - false otherwise
fn is_alpha(c: char) -> bool {
    c.is_ascii_alphabetic() || c == '_'
}

/// About
/// -----
/// - To verify that scanner is working, this is a simple function that scans all tokens from a source string and prints them
/// 
/// Parameters
/// ----------
/// - source (&str)
///     - Name of the file to be scanned
/// 
/// Panics
/// ------
/// - None
/// 
/// Returns
/// -------
/// - None
///     - Prints off all the tokens from `source`
fn print_tokens(source: &str) {
    let mut scanner = Scanner::init_scanner(source);
    let mut line: usize = 0;

    loop {
        let token = scanner.scan_token();

        if token.line != line {
            print!("{:4} ", token.line);
            line = token.line;
        } else {
            print!("   | ");
        }

        println!("{:?}, {:?}", token.token_type, String::from_utf8(token.value.clone()));

        match token.token_type {
            TokenType::TokenEof => break,
            _ => {}
        }
    }
}

