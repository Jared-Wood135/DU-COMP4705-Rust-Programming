/// About
/// -----
/// - Numerous token identifiers for abstract syntax of the programming language
#[derive(Debug, Clone, Copy, PartialEq)]
enum TokenType {
    // single character
    TokenLeftParen, TokenRightParen,
    TokenLeftBrace, TokenRightBrace,
    TokenComma, TokenDot, TokenSemicolon,
    TokenPlus, TokenMinus, TokenStar, TokenSlash,
    // one or two characters
    TokenNot, TokenNotEqual,
    TokenEqual, TokenEqualEqual,
    TokenLess, TokenLessEqual,
    TokenGreater, TokenGreaterEqual,
    // literals
    TokenIdentifier, TokenString, TokenNumber,
    // keywords
    TokenIf, TokenElse, TokenTrue, TokenFalse,
    TokenVar, TokenPrint, TokenNil,
    // ... more keywords ...
    // special
    TokenError, TokenEof,
}

