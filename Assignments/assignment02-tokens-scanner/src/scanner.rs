/// About
/// -----
/// - Represents a specific token generated by the scanner
/// 
/// Variables
/// ---------
/// - token_type (TokenType)
///     - The type of token
/// - value (Vec<u8>)
///     - The value of this token
/// - line (usize)
///     - The line this token was on
#[derive(Debug, Clone)]
struct Token {
    token_type: TokenType,
    value: Vec<u8>,
    line: usize,
}


/// About
/// -----
/// - Represents the current state of the scanning process
/// 
/// Variables
/// ---------
/// - source_code (Vec<u8>)
///     - Converted bytes of the file being scanned
/// - start (usize)
///     - The index of the current token being scanned
/// - current (usize)
///     - The index of the current character being scanned
/// - line (usize)
///     - The line that is currently being scanned
struct Scanner {
    source_code: Vec<u8>, 
    start: usize, 
    current: usize, 
    line: usize,
}

impl Scanner {
    /// About
    /// -----
    /// - Initializes the Scanner to represent the start of `source`
    /// 
    /// Parameters
    /// ----------
    /// - source (&str)
    ///     - The filename to be scanned and converted into bytes as `source_code` in `Scanner` structure
    /// 
    /// Panics
    /// ------
    /// - None
    /// 
    /// Returns
    /// -------
    /// - Scanner
    ///     - `Scanner` object representing and maintaining `source` as it is scanned
    fn init_scanner(source: &str) -> Scanner {
        Scanner {
            source_code: source.as_bytes().to_vec(),
            start: 0,
            current: 0,
            line: 1,
        }
    }

    /// About
    /// -----
    /// - Returns true if there are no more characters in the source code to examine, and false otherwise
    /// 
    /// Parameters
    /// ----------
    /// - &self
    ///     - The `Scanner` object being scanned
    /// 
    /// Panics
    /// ------
    /// - None
    /// 
    /// Returns
    /// -------
    /// - bool
    ///     - True if at the end of `source`
    ///     - False otherwise
    fn is_at_end(&self) -> bool {
        self.current >= self.source_code.len()
    }

    /// About
    /// -----
    /// - Returns the current character in the source code vector
    /// - This method should produce '\0' if there are no more characters to process
    /// 
    /// Parameters
    /// ----------
    /// - &self
    ///     - The `source` being scanned
    /// 
    /// Panics
    /// ------
    /// - None
    /// 
    /// Returns
    /// -------
    /// - char
    ///     - '\0' if at the end of `source`
    ///     - Otherwise current char
    fn peek(&self) -> char {
        if self.is_at_end() {
            '\0'
        } 
        else {
            self.source_code[self.current] as char
        }
    }

    /// About
    /// -----
    /// - Returns the character after the current character in the source code vector
    /// - This method should produce '\0' if there is no such character to process
    /// 
    /// Parameters
    /// ----------
    /// - &self
    ///     - `Scanner` object being scanned
    /// 
    /// Panics
    /// ------
    /// - None
    /// 
    /// Returns
    /// -------
    /// - char
    ///     - '\0' if at the end of `source`
    ///     - Otherwise current char
    fn peek_next(&self) -> char {
        if self.current + 1 >= self.source_code.len() {
            '\0'
        } 
        else {
            self.source_code[self.current + 1] as char
        }
    }

    /// About
    /// -----
    /// - Returns the current character in the source code vector and advances the Scanner to the next character to be processed
    /// 
    /// Parameters
    /// ----------
    /// - $mut self
    ///     - The mutable `Scanner` object being scanned
    /// 
    /// Panics
    /// ------
    /// - None
    /// 
    /// Returns
    /// -------
    /// - char
    ///     - The current character in the source code vector
    fn advance(&mut self) -> char {
        let c = self.source_code[self.current] as char;
        self.current += 1;
        c
    }

    /// About
    /// -----
    /// - Ignores characters as long as the character is a space, line feed, tab, or carriage return character
    /// - This will also ignore comments
    /// 
    /// Parameters
    /// ----------
    /// - &mut self
    ///     - Mutable `Scanner` object being scanned
    /// 
    /// Panics
    /// ------
    /// - None
    /// 
    /// Returns
    /// -------
    /// - None
    fn skip_whitespace(&mut self) {
        loop {
            if self.is_at_end() { return; }
            match self.peek() {
                ' ' | '\t' | '\r' => { self.advance(); }
                '\n' => {
                    self.line += 1;
                    self.advance();
                }
                '/' => {
                if self.peek_next() == '/' {
                    // comment: skip until end of line
                    while !self.is_at_end()
                    && self.peek() != '\n'
                        {
                            self.advance();
                        }
                } 
                else {
                    return; // a lone '/' is division
                }
                }
                _ => return,
            }
        }
    }

    /// About
    /// -----
    /// - The Scanner continues to skip characters until the closing " of a literal string is reached
    /// - Once the closing " is skipped, the method should return a TokenString token
    /// - If the Scanner reaches the end of the source code before finding a closing ", the method should return an error_token containing the message "Unterminated String Literal"
    /// 
    /// Parameters
    /// ----------
    /// - &mut self
    ///     - Mutable `Scanner` object being scanned
    /// 
    /// Panics
    /// ------
    /// - None
    /// 
    /// Returns
    /// -------
    /// - Token
    ///     - TokenString representing the detected string literal
    fn get_literal_string(&mut self) -> Token {
        // opening " was already consumed
        while !self.is_at_end() && self.peek() != '"' {
            if self.peek() == '\n' {
                self.line += 1;
            }
            self.advance();
        }
        if self.is_at_end() {
            return self.error_token("Unterminated String Literal");
        }
        self.advance(); // closing "
        self.make_token(TokenType::TokenString)
    }

    /// About
    /// -----
    /// - The Scanner skips any number of digit characters, followed by a decimal point character . and then any number of digit characters
    /// - The method should then return a TokenNumber token
    /// 
    /// Parameters
    /// ----------
    /// - &mut self
    ///     - Mutable `Scanner` object
    /// 
    /// Panics
    /// ------
    /// - None
    /// 
    /// Returns
    /// -------
    /// - Token
    ///     - TokenNumber representing the number detected
    fn get_literal_number(&mut self) -> Token {
        // first digit was already consumed by scan_token
        while !self.is_at_end()
        && self.peek().is_ascii_digit()
        {
            self.advance();
        }
        // look for a decimal point
        if self.peek() == '.'
        && self.peek_next().is_ascii_digit()
        {
            self.advance(); // consume the '.'
            while !self.is_at_end()
            && self.peek().is_ascii_digit()
            {
                self.advance();
            }
        }
        self.make_token(TokenType::TokenNumber)
    }

    /// About
    /// -----
    /// - Skips any number of alphabetic characters or underscores
    /// - The method should then return a TokenIdentifier token
    /// 
    /// Parameters
    /// ----------
    /// - &mut self
    ///     - Mutable `Scanner` object being scanned
    /// 
    /// Panics
    /// ------
    /// - None
    /// 
    /// Returns
    /// -------
    /// - Token
    ///     - TokenIdentifier representing the resepective detected token
    fn get_identifier(&mut self) -> Token {
        // first letter was already consumed by scan_token
        while !self.is_at_end()
        && (self.peek().is_ascii_alphabetic()
        || self.peek() == '_'
        || self.peek().is_ascii_digit())
        {
            self.advance();
        }
        // check if it's a keyword
        let text = String::from_utf8(self.source_code[self.start..self.current].to_vec()).unwrap_or_default();
        let tt = match text.as_str() {
            "if" => TokenType::TokenIf,
            "else" => TokenType::TokenElse,
            "true" => TokenType::TokenTrue,
            "false" => TokenType::TokenFalse,
            "var" => TokenType::TokenVar,
            "print" => TokenType::TokenPrint,
            "nil" => TokenType::TokenNil,
            // ... more keywords ...
            _ => TokenType::TokenIdentifier,
        };
        self.make_token(tt)
    }

    /// About
    /// -----
    /// - Rakes a character as a parameter and determines if the given character matches the current character the Scanner will scan
    /// - If the character matches, then the Scanner should move to the next character and the method should return true
    /// - Otherwise, the Scanner should not move to the next character and the function should return false
    /// - If the Scanner is at the end of the source code, it should return false
    /// 
    /// Parameters
    /// ----------
    /// - &mut self
    ///     - Mutable `Scanner` object being scanned
    /// - expected (char)
    ///     - The expected next character for matching
    /// 
    /// Panics
    /// ------
    /// - None
    /// 
    /// Returns
    /// -------
    /// - bool
    ///     - true if the next character matches `expected`
    ///     - false if the next character does not match `expected` or is at the end of `source_code`
    fn match_next(&mut self, expected: char) -> bool {
        if self.is_at_end() { return false; }
        if self.peek() != expected { return false; }
        self.current += 1;
        true
    }

    /// About
    /// -----
    /// - When given a TokenType, creates a new Token
    /// - The new Token should contain the given TokenType
    /// - The value in the Token should be the vector of u8 from the Scanner start to the Scanner current in the Scanner source code (i.e. a vector of the bytes that make up the Token which was just scanned)
    /// - The line of the token should be the current line value stored in the Scanner
    /// 
    /// Parameters
    /// ----------
    /// - &self
    ///     - `Scanner` object being scanned
    /// - token_type (TokenType)
    ///     - `TokenType` to be created as `Token`
    /// 
    /// Panics
    /// ------
    /// - None
    /// 
    /// Returns
    /// -------
    /// - Token
    ///     - The `Token` representing `token_type`
    fn make_token(&self, token_type: TokenType) -> Token {
        Token {
            token_type,
            value: self.source_code[self.start..self.current].to_vec(),
            line: self.line,
        }
    }

    /// About
    /// -----
    /// - Similar to make_token except that the method takes an error message &str as a parameter and returns a TokenError token
    /// - This error message should be the value in the returned token
    /// - The line of the token should be the current line value stored in the Scanner
    /// 
    /// Parameters
    /// ----------
    /// - &self
    ///     - `Scanner` object being scanned
    /// - message (&str)
    ///     - The message to be associated with the error token
    /// 
    /// Panics
    /// ------
    /// - None
    /// 
    /// Returns
    /// -------
    /// - Token
    ///     - `Token` representing an error token`
    fn error_token(&self, message: &str) -> Token {
        Token {
            token_type: TokenType::TokenError,
            value: message.as_bytes().to_vec(),
            line: self.line,
        }
    }

    /// About
    /// -----
    /// - First, the scanner should skip any whitespace characters starting at the current position in the source code
    /// - Then set the Scanner start to be the Scanner current (current is after the end of any previous token's characters)
    /// - If the Scanner is at the end of the source code, produce and return a TokenEof token
    /// - Get the next character in the source code by calling the Scanner advance method
    /// - If that character is_alpha, call get_identifier
    /// - If that character is_numeric, call get_literal_number
    /// - Next, use a match expression on that character to handle the single character tokens: ( ) { } ; , . + - / * and return the appropriate token (use the make_token method)
    /// - In the same match expression, handle the beginning of the possible two-character tokens. Compare the character to ! = > < and then match again on the Scanner next character to see if the token is !=, ==, >=, or <=, and produce the tokens TokenNotEqual, TokenEqualEqual, TokenGreaterEqual, or TokenLessEqual as appropriate. If the next character doesn't match correctly, produce TokenNot, TokenEqual, TokenGreater, or TokenLess as appropriate
    /// - Finally, if the next character doesn't match anything, scan_token should produce an error_token with the message "Unknown character."
    /// 
    /// Parameters
    /// ----------
    /// - &mut self
    ///     - Mutable `Scanner` object being scanned
    /// 
    /// Panics
    /// ------
    /// - None
    /// 
    /// Returns
    /// -------
    /// - Token
    ///     - Creation of a token depending on what is detected
    fn scan_token(&mut self) -> Token {
        self.skip_whitespace();
        self.start = self.current;

        if self.is_at_end() {
            return self.make_token(TokenType::TokenEof);
        }

        let c = self.advance();
        if c.is_ascii_alphabetic() || c == '_' {
            return self.get_identifier();
        }
        if c.is_ascii_digit() {
            return self.get_literal_number();
        }
        match c {
            '(' => self.make_token(TokenType::TokenLeftParen),
            ')' => self.make_token(TokenType::TokenRightParen),
            '{' => self.make_token(TokenType::TokenLeftBrace),
            '}' => self.make_token(TokenType::TokenRightBrace),
            ',' => self.make_token(TokenType::TokenComma),
            '.' => self.make_token(TokenType::TokenDot),
            ';' => self.make_token(TokenType::TokenSemicolon),
            '+' => self.make_token(TokenType::TokenPlus),
            '-' => self.make_token(TokenType::TokenMinus),
            '*' => self.make_token(TokenType::TokenStar),
            '/' => self.make_token(TokenType::TokenSlash),
            '!' => {
                if self.match_next('=') {
                    self.make_token(TokenType::TokenNotEqual)
                } 
                else {
                    self.make_token(TokenType::TokenNot)
                }
            }
            '=' => {
                if self.match_next('=') {
                    self.make_token(TokenType::TokenEqualEqual)
                } 
                else {
                    self.make_token(TokenType::TokenEqual)
                }
            }
            '<' => {
                if self.match_next('=') {
                    self.make_token(TokenType::TokenLessEqual)
                } 
                else {
                    self.make_token(TokenType::TokenLess)
                }
            }
            '>' => {
                if self.match_next('=') {
                    self.make_token(TokenType::TokenGreaterEqual)
                } 
                else {
                    self.make_token(TokenType::TokenGreater)
                }
            }
            '"' => self.get_literal_string(),
            _ => self.error_token("Unknown character."),
        }
    }
}

